// Phorum escapes the message body (htmlspecialchars) before the format
// hooks run. Parsedown therefore never sees a real "<" or ">": quotes
// ("> text") stayed plain text, the HTML inserted by the editor buttons
// (<u>, <sup>, colour, size, centring) and by the BBCode conversion was
// shown as raw tags, and code blocks were escaped twice. The functions
// below restore these, and nothing else: every other tag stays text.
// ----------------------------------------------------------------------

define('LIBREFORUM_MARKDOWN_MARK', "\x1A");

// "&gt; text" at the start of a line is a Markdown quote. Nested quotes
// ("&gt; &gt; text") too. A ">" glued to the text (">:D<") is left alone.
// A quote ends at the first line that does not start with ">": Markdown
// would carry on the quote ("lazy continuation"), and a reply written just
// under the quoted text would be shown as part of it.
function libreforum_markdown_quotes($body)
{
    // Fenced code blocks are left untouched.
    $parts = preg_split('/(^ {0,3}(?:```|~~~).*?(?:^ {0,3}(?:```|~~~)[^\n]*$|\z))/ms',
                        $body, -1, PREG_SPLIT_DELIM_CAPTURE);
    foreach ($parts as $k => $part) {
        if ($k % 2 == 1) continue;
        $part = preg_replace_callback(
            '/^( {0,3})((?:&gt; ?)*&gt;)(?= |$)/m',
            function ($m) { return $m[1] . str_replace('&gt;', '>', $m[2]); },
            $part
        );
        $parts[$k] = preg_replace('/^( {0,3}>[^\n]*)\n(?! {0,3}>|\s*\n|\s*$)/m', "$1\n\n", $part);
    }
    return implode('', $parts);
}

// Validate one escaped tag and return its safe HTML form, or NULL.
// Returns array(group, html) where group pairs an opening tag with its
// closing tag, or is '' for a tag that stands alone (br, img).
function libreforum_markdown_tag($closing, $name, $attrs)
{
    $name  = strtolower($name);
    $attrs = trim($attrs);

    if ($closing) {
        if ($attrs !== '') return NULL;
        $close = array('u' => '</u>', 'sub' => '</sub>', 'sup' => '</sup>',
                       'small' => '</small>', 'span' => '</span>',
                       'div' => '</span>', 'center' => '</span>', 'a' => '</a>');
        return isset($close[$name]) ? array($name, $close[$name]) : NULL;
    }

    switch ($name) {
        case 'u': case 'sub': case 'sup': case 'small':
            return $attrs === '' ? array($name, "<$name>") : NULL;

        case 'br':
            return ($attrs === '' || $attrs === '/') ? array('', '<br />') : NULL;

        case 'center':
            return $attrs === ''
                 ? array('center', '<span style="display: block; text-align: center;">') : NULL;

        case 'div':
            if (!preg_match('/^align=(&quot;|\'|)(left|right|center|justify)\1$/i', $attrs, $m)) return NULL;
            return array('div', '<span style="display: block; text-align: ' . strtolower($m[2]) . ';">');

        case 'span':
            if (!preg_match('/^style=(&quot;|\')(.*?)\1$/i', $attrs, $m)) return NULL;
            $css = array();
            foreach (explode(';', $m[2]) as $decl) {
                if (!preg_match('/^\s*(color|font-size)\s*:\s*(.+?)\s*$/i', $decl, $d)) continue;
                $prop = strtolower($d[1]);
                $val  = strtolower($d[2]);
                if ($prop == 'color' && preg_match('/^(#[0-9a-f]{3}|#[0-9a-f]{6}|[a-z]{3,20})$/', $val)) {
                    // Also as a custom property, so that a dark theme can
                    // lighten colours chosen for a white background.
                    $css[] = "color: $val";
                    $css[] = "--libreforum-color: $val";
                } elseif ($prop == 'font-size') {
                    $keywords = array('xx-small', 'x-small', 'small', 'medium', 'large', 'x-large', 'xx-large');
                    if (in_array($val, $keywords)) {
                        $css[] = "font-size: $val";
                    } elseif (preg_match('/^(\d{1,3})(px|pt|%)?$/', $val, $n)) {
                        // A bare number from BBCode [size=N]: 1 to 7 are the old
                        // HTML font sizes, larger values are pixels.
                        $v = (int) $n[1];
                        if (empty($n[2]) && $v >= 1 && $v <= 7) {
                            $css[] = 'font-size: ' . $keywords[$v - 1];
                        } elseif ($v >= 6 && $v <= 72) {
                            $css[] = "font-size: $v" . (empty($n[2]) ? 'px' : $n[2]);
                        }
                    }
                }
            }
            return $css ? array('span', '<span style="' . implode('; ', $css) . ';">') : NULL;

        case 'a':
            $url = libreforum_markdown_url($attrs, 'href');
            return $url === NULL ? NULL
                 : array('a', '<a href="' . htmlspecialchars($url) . '" rel="nofollow noopener" target="_blank">');

        case 'img':
            $url = libreforum_markdown_url($attrs, 'src');
            if ($url === NULL) return NULL;
            $url = preg_replace('!^http://!i', 'https://', $url);
            $alt = '';
            if (preg_match('/\balt=(&quot;|\')(.*?)\1/i', $attrs, $m)) {
                $alt = htmlspecialchars(libreforum_markdown_attr_value($m[2]));
            }
            return array('', '<img src="' . htmlspecialchars($url) . '" alt="' . $alt . '" />');
    }
    return NULL;
}

// The value of an attribute typed in a message: undo Phorum's escaping,
// then the HTML entities the author may have written ("&amp;" in a URL).
function libreforum_markdown_attr_value($escaped)
{
    return html_entity_decode(html_entity_decode($escaped, ENT_QUOTES, 'UTF-8'), ENT_QUOTES, 'UTF-8');
}

// The URL of an href/src attribute, if it is an absolute web or mail URL.
function libreforum_markdown_url($attrs, $attr)
{
    if (!preg_match('/\b' . $attr . '\s*=\s*(&quot;|\')(.*?)\1/i', $attrs, $m)) return NULL;
    $url = trim(libreforum_markdown_attr_value($m[2]));
    if (!preg_match('!^(https?://|ftp://|mailto:)[^\s"<>]+$!i', $url)) return NULL;
    return $url;
}

// Before Parsedown: replace the allowed escaped tags by placeholders. An
// opening tag is kept only if its closing tag follows, so a stray "<u>"
// in a message does not underline the rest of the page.
function libreforum_markdown_protect_html($body)
{
    $saved = array();
    if (strpos($body, '&lt;') === FALSE) return array($body, $saved);

    preg_match_all('/&lt;(\/?)([a-zA-Z][a-zA-Z0-9]*)((?:(?!&lt;|&gt;)[^<>\n])*)&gt;/',
                   $body, $matches, PREG_SET_ORDER | PREG_OFFSET_CAPTURE);
    $keep = array();
    $stacks = array();
    foreach ($matches as $i => $m) {
        $tag = libreforum_markdown_tag($m[1][0] === '/', $m[2][0], $m[3][0]);
        if ($tag === NULL) continue;
        list($group, $html) = $tag;
        if ($group === '') {
            $keep[$i] = $html;
        } elseif ($m[1][0] === '/') {
            if (!empty($stacks[$group])) {
                list($j, $open_html) = array_pop($stacks[$group]);
                $keep[$j] = $open_html;
                $keep[$i] = $html;
            }
        } else {
            $stacks[$group][] = array($i, $html);
        }
    }
    // A link that is never closed: show it as a plain link to its URL.
    // Left as text, its URL would be auto-linked by Parsedown together
    // with the escaped quote and bracket that follow it.
    if (!empty($stacks['a'])) {
        foreach ($stacks['a'] as $open) {
            list($j, $open_html) = $open;
            preg_match('/href="([^"]*)"/', $open_html, $h);
            $keep[$j] = $open_html . $h[1] . '</a>';
        }
    }
    if (!$keep) return array($body, $saved);

    // Rebuild from the end, so that the offsets stay valid.
    krsort($keep);
    foreach ($keep as $i => $html) {
        $text = $matches[$i][0][0];
        $offset = $matches[$i][0][1];
        $n = count($saved);
        $saved[$n] = array($html, $text);
        $mark = LIBREFORUM_MARKDOWN_MARK . $n . LIBREFORUM_MARKDOWN_MARK;
        $body = substr_replace($body, $mark, $offset, strlen($text));
    }
    return array($body, $saved);
}

// After Parsedown: put the allowed tags back, as HTML in the text and as
// the original text inside code. Parsedown escapes code once more, on a
// body that Phorum had already escaped: undo that second level.
function libreforum_markdown_restore_html($html, $saved)
{
    $mark = LIBREFORUM_MARKDOWN_MARK;
    $restore = function ($text, $as_text) use ($saved, $mark) {
        if (!$saved || strpos($text, $mark) === FALSE) return $text;
        return preg_replace_callback("/$mark(\\d+)$mark/",
            function ($m) use ($saved, $as_text) {
                if (!isset($saved[$m[1]])) return '';
                return $as_text ? $saved[$m[1]][1] : $saved[$m[1]][0];
            }, $text);
    };
    $double = '/&amp;(lt|gt|amp|quot|#0?39);/';

    $parts = preg_split('#(<code\b[^>]*>.*?</code>)#s', $html, -1, PREG_SPLIT_DELIM_CAPTURE);
    foreach ($parts as $k => $part) {
        if ($k % 2 == 1) {
            // Code: undo the second escaping, and give back the original text.
            $parts[$k] = $restore(preg_replace($double, '&$1;', $part), TRUE);
            continue;
        }
        $pieces = preg_split('/(<[^>]*>)/', $part, -1, PREG_SPLIT_DELIM_CAPTURE);
        foreach ($pieces as $p => $piece) {
            if ($p % 2 == 1) {
                // A tag built by Parsedown: its attributes (link and image
                // URLs) were escaped twice too. Only text may go back into
                // it, never HTML.
                $pieces[$p] = $restore(preg_replace($double, '&$1;', $piece), TRUE);
            } else {
                $pieces[$p] = $restore($piece, FALSE);
            }
        }
        $parts[$k] = implode('', $pieces);
    }
    return implode('', $parts);
}

